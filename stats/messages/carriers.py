#!/usr/bin/env python3
"""Carriers: values handed from a module's received messages to its sent ones, identified by a key (argmatch's
-carriers; dump_ancestors/argmatch/README.md, "Carriers", says what a carrier and its key are). A module's carriers
are its module.py's CARRIERS (modules/README.md).

A module's events get the carrier keys of the argmatch calls attributed to them (step 5's matches.calls.csv rows that
have carriers):
- received messages, by "stamp": a call made while a handler served a request (its `request` column, from the
  goroutine labels the ConfTamer patch to net/http sets: conftamer/contexttrack/README.md) is attributed to that
  request's "Request received" event, the one with that context ID. "inherited" counts those made on a goroutine the
  handler started (`request_goroutine` isn't the call's own). A received response gets none: what a client does with
  a response once it has it isn't attributed to the response (no "current response" rule);
- sent messages, by "chain": a call whose frame, with all its older frames, is on the event's stack or ancestry, as
  step 6's join.py joins calls to events (its key). Not received ones: a call that sends a request is on the stack
  of the response it receives too, which would make the response "carry" into its own request.
message_paths.py adds an edge X -> Y within a module when an event of X, received by it, and an event of Y, sent by
it, share a carrier key (edge kind "carrier").

Usage (a report of each module's carrier calls, the events they're attributed to, and the edges they add):
uv run --with pandas --with networkx --with tabulate --with matplotlib --with pyyaml --with numpy
python carriers.py --run <paramtrack --out dir> [--api-ids f] [--external f] [--out <file.md>]
"""

import collections
import csv
import json
import os
import sys

sys.path.insert(0, "/home/emily/projects/config_tracing/dump_ancestors/argmatch-labels")
import join  # noqa: E402  (argmatch-labels' join.py: chain)

csv.field_size_limit(1 << 30)


def _key(frames):
    return tuple(t[:3] for t in frames)  # (join.py's key: kinds, goroutines and offsets)


def _goroutine(ancestry):
    return ancestry.split("\n", 1)[0].split()[-1]  # "goroutine N" => N


class Calls:
    """A module's argmatch calls that have carriers (step 5's matches.calls.csv; none for a run from before argmatch
    reported carriers), indexed to attribute them to events (see the top)"""

    def __init__(self, calls_path):
        self.calls = []
        if os.path.exists(calls_path):
            with open(calls_path, newline="") as f:
                self.calls = [c for c in csv.DictReader(f) if c.get("carriers")]
        self.by_request = collections.defaultdict(list)  # context ID => calls stamped with it
        self.by_chain = collections.defaultdict(list)  # join.py's key => calls
        for c in self.calls:
            c["keys"] = set(json.loads(c["carriers"]))
            c["inherited"] = bool(c["request"]) and c["request_goroutine"] != _goroutine(c["ancestry"])
            if c["request"]:
                self.by_request[c["request"]].append(c)
            ch = join.chain(c["stack"], c["ancestry"])
            if ch[0][0] == "frame":  # (else its frame was elided: join.py can't place it either)
                self.by_chain[(ch[0][1], c["function"], _key(ch[1:]))].append(c)

    def __bool__(self):
        return bool(self.calls)

    def attributed(self, ev, received):
        """The calls attributed to an event (a dict of events.jsonl), each with how: [(call, "stamp" | "chain")];
        received: whether the module received the event's message (see the top)"""
        out = []
        if received:
            if ev.get("kind") == "Request received":
                cid = (ev.get("context") or {}).get("context_id")
                out += [(c, "stamp") for c in self.by_request.get(cid, [])]
        elif self.by_chain and ev.get("stack"):
            ch = join.chain(ev["stack"], ev.get("ancestry", ""))
            for i, (kind, gid, _, names) in enumerate(ch):
                if kind == "frame":
                    older = _key(ch[i + 1:])
                    out += [(c, "chain") for fn in set(names) for c in self.by_chain.get((gid, fn, older), [])]
        return out


def module_calls(run, module):
    return Calls(f"{run}/{module}/5-matches/matches.calls.csv")


def report(run, g, calls, attributions):
    """The report's lines: per module, its carrier calls, the events they're attributed to, and the carrier edges
    (g: message_paths.build's graph; calls: module => Calls; attributions: module => [(kind, node label, call, how)])"""
    import message_paths  # (it imports this file)
    lines = [f"# Carriers ({run})", "", "Generated by stats/messages/carriers.py (its docstring says what's counted).", ""]
    edges = [(a, b, d) for a, b, d in g.edges(data=True) if "carrier" in d.get("kinds", ())]
    for module, cs in sorted(calls.items()):
        lines += [f"## {module}", ""]
        if not cs:
            lines += ["No calls with carriers.", ""]
            continue
        fns = collections.Counter(c["function"].rsplit("/", 1)[-1] for c in cs.calls)
        stamped = [c for c in cs.calls if c["request"]]
        keys = set().union(*(c["keys"] for c in cs.calls))
        lines += [f"- calls with carriers: {len(cs.calls)} ({', '.join(f'{f} {n}' for f, n in fns.most_common())}); "
                  f"stamped with a request: {len(stamped)} (inherited: {sum(c['inherited'] for c in stamped)}); "
                  f"distinct keys: {len(keys)}", ""]
        att = attributions.get(module, [])
        by = collections.Counter((kind, lbl, how) for kind, lbl, _, how in att)
        lines += ["Events with carriers (an event kind and node, how its calls were attributed, (event, call) pairs):",
                  "", "| event | node | how | pairs |", "|---|---|---|---:|"]
        lines += [f"| {k} | `{lbl}` | {how} | {n} |" for (k, lbl, how), n in sorted(by.items())] + [""]
        mine = [(a, b, d) for a, b, d in edges if module in d.get("carrier_modules", ())]
        lines += [f"Carrier edges in {module} ({len(mine)}; \"new\": no other edge kind joins them):", "",
                  "| received | sent | shared keys | new |", "|---|---|---:|---|"]
        for a, b, d in sorted(mine, key=lambda e: (message_paths.label(e[0]), message_paths.label(e[1]))):
            lines.append(f"| `{message_paths.label(a)}` | `{message_paths.label(b)}` | "
                         f"{len(d['carrier_keys'])} | {'yes' if d['kinds'] == {'carrier'} else 'no'} |")
        lines.append("")
    return lines


def main():
    import argparse
    import message_paths  # (it imports this file)
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    message_paths.add_args(ap)
    ap.add_argument("--out", help="the report (markdown); default stdout")
    a = ap.parse_args()
    g = message_paths.build_from_args(a)
    text = "\n".join(report(a.run, g, g.graph["carrier_calls"], g.graph["carrier_attributions"]))
    if a.out:
        open(a.out, "w").write(text)
        print(f"wrote {a.out}")
    else:
        print(text)


if __name__ == "__main__":
    main()
