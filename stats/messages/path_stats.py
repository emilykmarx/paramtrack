#!/usr/bin/env python3
"""Statistics of message_paths.py's graph and paths, for a paramtrack run (message_paths.py's docstring says what its
nodes, the message labels, and its paths are):
- message labels matched between each pair of modules: nodes whose sender and receiver are two different modules,
  per (sender, receiver), requests and responses;
- paths: how many maximal paths, the longest, and a histogram of their lengths (all lengths: message_paths.py's
  --min-length doesn't apply);
- external endpoints in paths: per endpoint, its message labels, how many paths contain one, and the longest;
- per message label, as each module logged it (the sender's sent type, the receiver's received type: several nodes
  can share one): its events, the time they were observed over (the first event's ts to the last's), and events per
  second; in <out>.rates.csv, with a summary in <out>.md;
- unmatched message labels: those only one side logged, by module, external (their peer named) or unexplained.

Usage: uv run --with pandas --with networkx --with tabulate --with matplotlib --with pyyaml --with numpy
python path_stats.py --run <paramtrack --out dir> [--api-ids f] [--external f] --out <prefix>
writes <prefix>.md and <prefix>.rates.csv
"""

import argparse
import collections
import csv

import message_paths as mp  # (next to this file: the graph and its paths)


def is_module(end, modules):
    """Whether a node's sender or receiver is a module (a type logged by several modules names them all, a;b)"""
    return all(m in modules for m in end.split(";"))


def endpoints(n, modules):
    """The external endpoints a node has as sender or receiver: those that aren't modules, a name joined with " + "
    (a type with several kinds of peer) split into its names"""
    return {e for end in (n.snd, n.rcv) if not is_module(end, modules) for e in end.split(" + ")}


def side_label(side, typ, nodes):
    """A message type as one module logged it (match_messages' type: a received request's route pattern, a sent
    request's concrete path), with the client side's host (types differ by it, e.g. each node exporter Prometheus
    scrapes) and the endpoints of its nodes: <peers> req|resp <method> <path> [<code>] [(host <host>)]"""
    req = typ if side.endswith("req") else typ[2]
    ends = " + ".join(sorted({f"{n.snd}->{n.rcv}" for n in nodes})) or "?"
    code = f" {typ[1]}" if side.endswith("resp") else ""
    host = f" (host {req[2]})" if req[2] else ""
    return f"{ends} {'req' if side.endswith('req') else 'resp'} {req[1]} {req[3]}{code}{host}"


def rates(g):
    """One row per message type as a module logged it: its events, the time span they were observed over, and events
    per second (none for a single event, or events without ts). Per type, not per node: several nodes can share one
    side's type (e.g. one route pattern on the receiver), and its events can't be split between them"""
    out = []
    for (module, side, typ), (count, first, last) in g.graph["events"].items():
        span = (last - first) / 1e9 if first is not None and last is not None else None
        out.append({"label": side_label(side, typ, g.graph["nodes_of"].get((side, typ), [])), "module": module,
                    "kind": mp.SIDE_KIND[side], "events": count, "span_s": round(span, 3) if span is not None else "",
                    "per_s": round(count / span, 4) if span else ""})
    return sorted(out, key=lambda r: (r["label"], r["module"], r["kind"]))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mp.add_args(ap)
    ap.add_argument("--out", required=True, help="output prefix: <out>.md, <out>.rates.csv")
    a = ap.parse_args()
    g = mp.build_from_args(a)
    modules = set(mp.um.module_events(a.run))
    lines = [f"# Message path statistics ({a.run})", "",
             f"Generated by stats/messages/path_stats.py --run {a.run}"
             + (f" --api-ids {a.api_ids}" if a.api_ids else "") + (f" --external {a.external}" if a.external else ""),
             "", f"Graph: {g.number_of_nodes()} message labels (nodes), {g.number_of_edges()} edges.", ""]

    # Message labels matched between each pair of modules
    pairs = collections.Counter((n.snd, n.rcv, n.message) for n in g
                                if is_module(n.snd, modules) and is_module(n.rcv, modules) and n.snd != n.rcv)
    lines += ["## Message labels matched between modules", "",
              "Nodes whose sender and receiver are two different modules (not a module with itself).", "",
              "| sender | receiver | requests | responses |", "|---|---|---:|---:|"]
    for s, r in sorted({(s, r) for s, r, _ in pairs}):
        lines.append(f"| {s} | {r} | {pairs[(s, r, 'request')]} | {pairs[(s, r, 'response')]} |")
    lines += [f"| total | | {sum(v for k, v in pairs.items() if k[2] == 'request')} | "
              f"{sum(v for k, v in pairs.items() if k[2] == 'response')} |", ""]

    # Paths, and the external endpoints on them
    ends = {n: endpoints(n, modules) for n in g}
    lengths = collections.Counter()
    on_paths = collections.defaultdict(lambda: [0, 0, 0])  # endpoint => [paths, paths of >= 4 messages, longest]
    for p in mp.maximal_paths(g):
        lengths[len(p)] += 1
        for e in set().union(*(ends[n] for n in p)):
            c = on_paths[e]
            c[0] += 1
            c[1] += len(p) >= 4
            c[2] = max(c[2], len(p))
    total = sum(lengths.values())
    lines += ["## Paths", "", f"- Maximal paths: {total}; longest: {max(lengths) if lengths else 0} messages", "",
              "| length | paths | share |", "|---:|---:|---:|"]
    lines += [f"| {n} | {c} | {c / total:.1%} |" for n, c in sorted(lengths.items())] + [""]

    # External endpoints: how many message labels have each as sender or receiver, and how many paths contain one
    labels = collections.Counter(e for n in g for e in ends[n])
    lines += ["## External endpoints in paths", "",
              "Each external endpoint (a sender or receiver that isn't a module; names joined with ` + `, for "
              "messages from several kinds of peer, counted under each): the message labels with it as sender or "
              "receiver, the maximal paths containing any of them (all, and of at least 4 messages, "
              "message_paths.py's default --min-length), and the longest such path.", "",
              "| endpoint | message labels | paths | paths of >= 4 | longest path |", "|---|---:|---:|---:|---:|"]
    for e in sorted(labels, key=lambda e: (-on_paths[e][1], -on_paths[e][0], e)):
        c = on_paths[e]
        lines.append(f"| {e} | {labels[e]} | {c[0]} | {c[1]} | {c[2]} |")
    lines.append("")

    # Events per second, per message label and module
    rows = rates(g)
    with open(f"{a.out}.rates.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    timed = [r for r in rows if r["per_s"] != ""]
    lines += ["## Events per second, per message label and module", "",
              f"Every message type as a module logged it, in {a.out}.rates.csv: its events, the seconds from the "
              f"first's ts to the last's, and events per second. {len(rows)} rows; {len(rows) - len(timed)} have a "
              "single event (no rate).", "", "Highest rates:", "",
              "| label | module | kind | events | seconds | per second |",
              "|---|---|---|---:|---:|---:|"]
    for r in sorted(timed, key=lambda r: -r["per_s"])[:15]:
        lines.append(f"| `{r['label']}` | {r['module']} | {r['kind']} | {r['events']} | {r['span_s']} | {r['per_s']} |")
    lines.append("")

    # Unmatched message labels
    un = collections.Counter()
    for row, name in g.graph["unmatched"]:
        side = "snd" if row["status"] == "unmatched-sender" else "rcv"
        un[(row[f"{side}_components"], "external" if name else "unexplained")] += 1
    lines += ["## Unmatched message labels", "",
              "Types only one side logged (unmatched_messages.py's), by the module that logged them: external if "
              "their peer is named, else unexplained.", "", "| module | external | unexplained |", "|---|---:|---:|"]
    for m in sorted({m for m, _ in un}):
        lines.append(f"| {m} | {un[(m, 'external')]} | {un[(m, 'unexplained')]} |")
    lines += [f"| total | {sum(v for k, v in un.items() if k[1] == 'external')} | "
              f"{sum(v for k, v in un.items() if k[1] == 'unexplained')} |", ""]

    open(f"{a.out}.md", "w").write("\n".join(lines))
    print(f"wrote {a.out}.md, {a.out}.rates.csv")


if __name__ == "__main__":
    main()
